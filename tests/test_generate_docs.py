"""Tests for scripts/generate_docs.py (the docs/reference/ generator)."""

import importlib.util
import inspect
import sys
from pathlib import Path

_SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "generate_docs.py"
_SPEC = importlib.util.spec_from_file_location("generate_docs", _SCRIPT)
assert _SPEC is not None and _SPEC.loader is not None
docs = importlib.util.module_from_spec(_SPEC)
sys.modules["generate_docs"] = docs  # dataclasses resolve annotations via sys.modules
_SPEC.loader.exec_module(docs)


def test_index_and_pages_are_written(tmp_path: Path) -> None:
    docs.write_docs(tmp_path)
    index = (tmp_path / "index.md").read_text()
    assert "ApiKey" in index and "Bearer" in index and "Generated by" in index
    names = {p.name for p in tmp_path.iterdir()}
    for page, _title in docs.RESOURCE_PAGES:
        assert f"{page}.md" in names
        assert f"({page}.md)" in index
    for page, _module, _title in docs.MODULE_PAGES:
        assert f"{page}.md" in names


def test_every_public_method_is_documented(tmp_path: Path) -> None:
    docs.write_docs(tmp_path)
    client = docs.ReportnetClient("https://example.invalid", "t")
    for page, _title in docs.RESOURCE_PAGES:
        text = (tmp_path / f"{page}.md").read_text()
        cls = type(getattr(client, page))
        methods = [n for n, _ in inspect.getmembers(cls, inspect.isfunction) if n[0] != "_"]
        assert methods
        for name in methods:
            assert f"### {name}\n" in text, f"{page}.{name} missing"
    for page, module, _title in docs.MODULE_PAGES:
        text = (tmp_path / f"{page}.md").read_text()
        for name, func in inspect.getmembers(module, inspect.isfunction):
            if name[0] != "_" and func.__module__ == module.__name__:
                assert f"### {name}\n" in text


def test_roles_are_parsed_or_marked_not_stated(tmp_path: Path) -> None:
    docs.write_docs(tmp_path)
    datasets = (tmp_path / "datasets.md").read_text()
    assert "| Design dataset | CUSTODIAN, STEWARD, EDITOR WRITE |" in datasets
    assert docs.NO_ROLES in datasets
    assert "GET /dataset/checkImportProcess/{datasetId}" in datasets
    assert "GET /dataschema/export" in (tmp_path / "dataset_schema.md").read_text()


def test_private_endpoints_are_not_documented(tmp_path: Path) -> None:
    docs.write_docs(tmp_path)
    for path in tmp_path.glob("*.md"):
        if path.name != "index.md":  # the index only explains their absence
            assert "/private/" not in path.read_text()


def test_caveats_refer_to_documented_names(tmp_path: Path) -> None:
    pages = docs.build_pages()[1]
    known = {d.name for v in pages.values() for d in v}
    known |= {f"{p}.{d.name}" for p, v in pages.items() for d in v}
    assert set(docs.CAVEATS) <= known


def test_output_is_deterministic(tmp_path: Path) -> None:
    first, second = tmp_path / "a", tmp_path / "b"
    docs.write_docs(first)
    docs.write_docs(second)
    files = sorted(p.name for p in first.iterdir())
    assert files == sorted(p.name for p in second.iterdir())
    for name in files:
        assert (first / name).read_bytes() == (second / name).read_bytes()
